-- Illustrative: verify incremental refresh eligibility in a real Snowflake account.
CREATE OR REPLACE DYNAMIC TABLE P2P_ANALYTICS.SILVER.PURCHASE_ORDER
 TARGET_LAG = '15 minutes' WAREHOUSE = P2P_WH REFRESH_MODE = INCREMENTAL
AS
SELECT EBELN AS PO_ID, BUKRS AS COMPANY_CODE, LIFNR AS VENDOR_ID,
 TRY_TO_DATE(BEDAT,'YYYYMMDD') AS PO_DATE, WAERS AS CURRENCY
FROM P2P_ANALYTICS.BRONZE.EKKO_EVENTS
QUALIFY ROW_NUMBER() OVER(PARTITION BY EBELN ORDER BY SOURCE_VERSION DESC,INGESTED_AT DESC)=1
 AND NOT IS_DELETED;
