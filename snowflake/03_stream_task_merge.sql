CREATE OR REPLACE TABLE P2P_ANALYTICS.SILVER.PO_STATUS (PO_ID VARCHAR, STATUS VARCHAR, UPDATED_AT TIMESTAMP_NTZ);
CREATE OR REPLACE TABLE P2P_ANALYTICS.BRONZE.PO_STATUS_EVENTS (PO_ID VARCHAR, STATUS VARCHAR, UPDATED_AT TIMESTAMP_NTZ);
CREATE OR REPLACE STREAM P2P_ANALYTICS.BRONZE.PO_STATUS_STREAM ON TABLE P2P_ANALYTICS.BRONZE.PO_STATUS_EVENTS APPEND_ONLY=TRUE;
CREATE OR REPLACE TASK P2P_ANALYTICS.SILVER.MERGE_PO_STATUS
 WAREHOUSE=P2P_WH WHEN SYSTEM$STREAM_HAS_DATA('P2P_ANALYTICS.BRONZE.PO_STATUS_STREAM')
AS MERGE INTO P2P_ANALYTICS.SILVER.PO_STATUS t
USING (SELECT PO_ID,STATUS,UPDATED_AT FROM P2P_ANALYTICS.BRONZE.PO_STATUS_STREAM
 QUALIFY ROW_NUMBER() OVER(PARTITION BY PO_ID ORDER BY UPDATED_AT DESC)=1) s
ON t.PO_ID=s.PO_ID
WHEN MATCHED AND s.UPDATED_AT>=t.UPDATED_AT THEN UPDATE SET STATUS=s.STATUS,UPDATED_AT=s.UPDATED_AT
WHEN NOT MATCHED THEN INSERT(PO_ID,STATUS,UPDATED_AT) VALUES(s.PO_ID,s.STATUS,s.UPDATED_AT);
