-- Minimal Gold example; full fact model requires EKPO, invoice and receipt ingestion.
CREATE OR REPLACE DYNAMIC TABLE P2P_ANALYTICS.GOLD.DIM_PURCHASE_ORDER
 TARGET_LAG='30 minutes' WAREHOUSE=P2P_WH REFRESH_MODE=AUTO
AS SELECT PO_ID, COMPANY_CODE, VENDOR_ID, PO_DATE, CURRENCY
FROM P2P_ANALYTICS.SILVER.PURCHASE_ORDER;
